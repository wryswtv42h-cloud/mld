function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export function initCodeNames(players) {
  const shuffled = shuffle(players);
  const half = Math.ceil(shuffled.length / 2);
  const teamRed = shuffled.slice(0, half);
  const teamBlue = shuffled.slice(half);

  const board = shuffle(WORDS).slice(0, 25);

  const colors = [];
  for (let i = 0; i < 9; i++) colors.push('red');
  for (let i = 0; i < 8; i++) colors.push('blue');
  for (let i = 0; i < 7; i++) colors.push('neutral');
  colors.push('assassin');

  const shuffledColors = shuffle(colors);
  const words = board.map((w, i) => ({
    word: w,
    color: shuffledColors[i],
    revealed: false
  }));

  return {
    game: 'codenames',
    players,
    teams: { red: teamRed, blue: teamBlue },
    clueGivers: { red: teamRed[0], blue: teamBlue[0] },
    words,
    currentTeam: 'red',
    currentClue: null,
    score: { red: 0, blue: 0 },
    finished: false,
    winner: null,
    log: ['بدأت كود نيمز بـ ' + players.length + ' لاعبين']
  };
}

export function handleCodeNamesAction(state, playerName, action) {
  const s = JSON.parse(JSON.stringify(state));

  const currentTeamPlayers = s.teams?.[s.currentTeam] || [];
  const clueGiver = s.clueGivers?.[s.currentTeam];
  const isClueGiver = playerName === clueGiver;
  const isTeamPlayer = currentTeamPlayers.includes(playerName);

  if (action.type === 'clue') {
    if(!isClueGiver || s.currentClue) return s;
    const number = Math.max(0, Math.min(9, Number(action.number)||0));
    const word = String(action.word||'').trim();
    if(!word || !number) return s;
    s.currentClue = { word, number, team: s.currentTeam };
    s.log.push(`الفريق ${s.currentTeam}: تلميح "${action.word}" × ${action.number}`);
  }

  if (action.type === 'guess') {
    if(isClueGiver || !isTeamPlayer || !s.currentClue) return s;
    const word = s.words[action.index];
    if (!word || word.revealed) return s;

    word.revealed = true;

    if (word.color === 'red') s.score.red++;
    if (word.color === 'blue') s.score.blue++;
    if (word.color === 'assassin') {
      s.finished = true;
      s.winner = s.currentTeam === 'red' ? 'blue' : 'red';
    }

    if (s.score.red >= 9) { s.finished = true; s.winner = 'red'; }
    if (s.score.blue >= 8) { s.finished = true; s.winner = 'blue'; }

    s.log.push(`${playerName} كشف "${word.word}" (${word.color})`);

    if (word.color !== s.currentTeam && word.color !== 'neutral') {
      s.currentTeam = s.currentTeam === 'red' ? 'blue' : 'red';
      s.currentClue = null;
    }
  }

  if (action.type === 'end-turn') {
    if(!isTeamPlayer) return s;
    s.currentTeam = s.currentTeam === 'red' ? 'blue' : 'red';
    s.currentClue = null;
  }

  return s;
}

