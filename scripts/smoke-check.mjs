import { readFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const root=process.cwd();
const read=path=>readFileSync(join(root,path),'utf8');
const mustExist=path=>assert.ok(existsSync(join(root,path)),`Missing required path: ${path}`);
const walk=dir=>readdirSync(join(root,dir)).flatMap(name=>{const path=join(dir,name);return statSync(join(root,path)).isDirectory()?walk(path):[path]});
for(const path of ['web/public/logo.svg.JPG','web/public/index.html','web/public/app.js','web/public/rebuild-polish.css','api/src/routes/games.js','api/src/socket/games.js','api/src/routes/bots.js','bot/src/index.js'])mustExist(path);
const html=read('web/public/index.html'),app=read('web/public/app.js'),gameRoute=read('api/src/routes/games.js'),gameSocket=read('api/src/socket/games.js'),bots=read('api/src/routes/bots.js');
assert.match(html,/logo\.svg\.JPG/,'Original logo must remain referenced.');
assert.match(html,/rebuild-polish\.css/,'Responsive polish stylesheet must be loaded.');
assert.match(app,/const ownerView=.*role.*owner/,'Owner role must bypass page maintenance locks.');
assert.match(app,/await getPageLocksSnapshot\(\)/,'Visitor lock settings must be fetched before rendering.');
assert.match(app,/game-seat-avatar/,'Game seats must render avatars.');
assert.match(app,/data-member="\'+esc\(p\.discordId\)/,'Game seat profile links must use Discord member IDs.');
assert.match(gameRoute,/discordId:req\.user\.discord_id\|\|null/,'New sessions must retain the host Discord ID.');
assert.match(gameRoute,/avatar:req\.user\.avatar\|\|null/,'New sessions must retain the host avatar.');
assert.match(gameSocket,/discordId:socket\.user\?\.discord_id\|\|null/,'Socket joins must retain the player Discord ID.');
assert.match(gameSocket,/avatar:socket\.user\?\.avatar\|\|null/,'Socket joins must retain player avatars.');
assert.match(bots,/req\.body\.commands\.slice\(0,500\)/,'Bot API must accept up to 500 custom prefix commands.');
assert.match(bots,/Object\.entries\(input\)\.slice\(0,1000\)/,'Bot API must accept 1000 command policy entries.');
const jsFiles=[...walk('api/src'),...walk('bot/src'),...walk('web/public')].filter(p=>p.endsWith('.js'));
assert.ok(jsFiles.length>0,'JavaScript files should be discovered.');
console.log(`MLD smoke checks passed; discovered ${jsFiles.length} JavaScript files.`);
